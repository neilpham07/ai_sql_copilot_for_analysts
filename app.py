def format_cdp_fields(fields: dict) -> str:
    lines = []
    for key, meta in fields.items():
        ops = ", ".join(meta["operators"])
        vals = ""
        if "values" in meta:
            vals = f" | values: {meta['values']}"
        lines.append(f"  {key} ({meta['type']}, operators: [{ops}]{vals}): {meta['label']}")
    return "\n".join(lines)


